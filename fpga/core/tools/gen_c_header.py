#!/usr/bin/env python3
"""Make the firmware's C header from the capture core's package (rtl/core_pkg.sv) and the TAG in rtl/top.sv.

    gen_c_header.py OUT.h            write
    gen_c_header.py --check OUT.h    exit 1 if OUT.h is not what would be written (for CI)

The package is the one place where the SPI protocol's numbers live; the firmware includes the result and
never spells an opcode itself.
"""
import re, sys, pathlib

HERE = pathlib.Path(__file__).resolve().parent.parent

def sv_number(tok):
    m = re.fullmatch(r"(\d+)?'([hdb])([0-9a-fA-F_]+)", tok)
    if m:
        return int(m.group(3).replace("_", ""), {"h": 16, "d": 10, "b": 2}[m.group(2)])
    if re.fullmatch(r"\d+", tok):
        return int(tok)
    return None

def evaluate(expr, known):
    """Numbers, known names, and | between them: all the package uses."""
    total = 0
    for part in expr.split("|"):
        part = part.strip()
        v = sv_number(part)
        if v is None:
            if part not in known:
                raise SystemExit(f"gen_c_header: cannot evaluate '{expr}'")
            v = known[part]
        total |= v
    return total

def parse():
    pkg = (HERE / "rtl/core_pkg.sv").read_text()
    items, known = [], {}          # (name, value, comment) in file order; ("", None, text) = a section title
    in_enum = False
    for line in pkg.splitlines():
        s = line.strip()
        m = re.match(r"// ---- (.*)", s)
        if m:
            items.append(("", None, m.group(1), False))
            continue
        m = re.match(r"localparam\s+(logic\s*(?:\[[^\]]*\])?|int(?:\s+unsigned)?)\s+(\w+)\s*=\s*([^;]+);\s*(?://\s*(.*))?", s)
        if m:
            v = evaluate(m.group(3), known)
            known[m.group(2)] = v
            items.append((m.group(2), v, m.group(4) or "", m.group(1).startswith("int")))
            continue
        if s.startswith("typedef enum"):
            in_enum = True
            continue
        if in_enum:
            if s.startswith("}"):
                in_enum = False
                continue
            m = re.match(r"(\w+)\s*=\s*([^,/\s]+),?\s*(?://\s*(.*))?", s)
            if m:
                v = evaluate(m.group(2), known)
                known[m.group(1)] = v
                items.append((m.group(1), v, m.group(3) or "", False))
    top = (HERE / "rtl/top.sv").read_text()
    m = re.search(r"parameter\s+logic\s*\[7:0\]\s+TAG\s*=\s*([^,\s]+)", top)
    if not m:
        raise SystemExit("gen_c_header: no TAG parameter in rtl/top.sv")
    return items, sv_number(m.group(1))

def render():
    items, tag = parse()
    out = ["/* GENERATED by fpga/core/tools/gen_c_header.py from rtl/core_pkg.sv and rtl/top.sv. Do not edit:",
           " * change the package and run the generator. The numbers of the SPI protocol between the firmware and",
           " * OpenScope's capture core. */",
           "#ifndef FPGA_CORE_REGS_H", "#define FPGA_CORE_REGS_H", "",
           f"#define FPGA_CORE_TAG                0x{tag:02X}u   /* the build this header was made with */"]
    for name, value, comment, decimal in items:
        if name == "":
            out += ["", f"/* {comment} */"]
            continue
        text = f"{value}u" if decimal else f"0x{value:02X}u"
        line = f"#define FPGA_CORE_{name:<18} {text}"
        out.append(f"{line:<44} /* {comment} */" if comment else line)
    out += ["", "#endif", ""]
    return "\n".join(out)

def main():
    args = sys.argv[1:]
    check = "--check" in args
    paths = [a for a in args if a != "--check"]
    if len(paths) != 1:
        raise SystemExit(__doc__)
    text, path = render(), pathlib.Path(paths[0])
    if check:
        if not path.exists() or path.read_text() != text:
            print(f"{path} is out of date: run gen_c_header.py {path}")
            sys.exit(1)
        print(f"{path} is up to date")
    else:
        path.write_text(text)
        print(f"wrote {path}")

if __name__ == "__main__":
    main()
