#!/usr/bin/env python3
"""Emulate stock V1.2.0's signal-generator builder and write the host-test fixture.

Runs the stock waveform builder (flash 0x08029E14) in unicorn, RAM only,
for a set of (waveform, amplitude, duty) cases, and writes the 100-sample
cycles it leaves at ms+0xE62 as tests/fixtures/siggen_stock_waves.h.
firmware/tests/test_siggen.c then requires siggen_wave_build() to match
every cycle code for code.

The case set is the parity study's (waves.json: every type at amp 30/10,
duty 50/20/0/100) plus amplitude edges for every type and dense duty
sweeps for the two duty-driven types.

Usage (needs `pip install unicorn` and a V1.2.0 APP image; nothing here
touches hardware):
  python3 scripts/gen_siggen_stock_waves.py APP_2C53T_V1.2.0_251015.bin \
      > firmware/tests/fixtures/siggen_stock_waves.h
"""
import struct
import sys

from unicorn import Uc, UcError, UC_ARCH_ARM, UC_MODE_THUMB, UC_MODE_MCLASS
from unicorn.arm_const import UC_ARM_REG_SP, UC_ARM_REG_LR

APP_BASE = 0x08007000
BUILDER = 0x08029E14
MS = 0x200000F8            # stock main state block
RET = 0x20041000           # fake return address (unmapped stop point)


def make_emu(image):
    mu = Uc(UC_ARCH_ARM, UC_MODE_THUMB | UC_MODE_MCLASS)
    mu.mem_map(APP_BASE, (len(image) + 0xFFF) & ~0xFFF)
    mu.mem_write(APP_BASE, image)
    mu.mem_map(0x20000000, 0x40000)
    mu.mem_map(0x20040000, 0x10000)
    return mu


def build(mu, wave, amp, duty):
    mu.mem_write(MS + 0xE62, b"\xEE" * 200)            # poison the buffer
    mu.mem_write(MS + 0xE58, bytes([1, wave]))          # enable, type
    mu.mem_write(MS + 0xE5C, struct.pack("<I", 1000))   # freq (unused here)
    mu.mem_write(MS + 0xE60, bytes([duty, amp]))        # duty, amplitude
    mu.reg_write(UC_ARM_REG_SP, 0x20050000)
    mu.reg_write(UC_ARM_REG_LR, RET | 1)
    mu.emu_start(BUILDER | 1, RET, count=500000)
    return struct.unpack("<100H", bytes(mu.mem_read(MS + 0xE62, 200)))


def cases():
    seen = set()
    def add(c):
        if c not in seen:
            seen.add(c)
            yield c
    for w in range(13):                                  # waves.json set
        for amp, duty in ((30, 50), (10, 50), (30, 20), (30, 0), (30, 100)):
            yield from add((w, amp, duty))
        for amp in (0, 1, 2, 7, 15, 29):                 # amplitude edges
            yield from add((w, amp, 37))
    for w in (1, 2):                                     # duty sweeps
        for duty in range(0, 101):
            yield from add((w, 30, duty))
        for duty in (1, 3, 33, 66, 97, 99):
            yield from add((w, 1, duty))
            yield from add((w, 13, duty))


def main():
    image = open(sys.argv[1], "rb").read()
    mu = make_emu(image)
    rows = []
    for w, amp, duty in cases():
        try:
            rows.append((w, amp, duty, build(mu, w, amp, duty)))
        except UcError as e:
            sys.exit(f"emulation failed for {w}/{amp}/{duty}: {e}")
    out = sys.stdout
    out.write("/* GENERATED by scripts/gen_siggen_stock_waves.py from stock V1.2.0\n"
              " * (builder 0x08029E14 emulated in unicorn). Do not edit by hand. */\n"
              "#ifndef SIGGEN_STOCK_WAVES_H\n#define SIGGEN_STOCK_WAVES_H\n\n"
              "#include <stdint.h>\n\n"
              "typedef struct { uint8_t wave, amp, duty; uint16_t code[100]; }"
              " siggen_stock_case_t;\n\n"
              "static const siggen_stock_case_t siggen_stock_cases[] = {\n")
    for w, amp, duty, code in rows:
        out.write("    { %d, %d, %d, {\n" % (w, amp, duty))
        for r in range(0, 100, 20):
            out.write("        " + ",".join(str(x) for x in code[r:r + 20]) + ",\n")
        out.write("    } },\n")
    out.write("};\n\n#define SIGGEN_STOCK_CASE_COUNT "
              "(sizeof(siggen_stock_cases) / sizeof(siggen_stock_cases[0]))\n\n"
              "#endif\n")


if __name__ == "__main__":
    main()
