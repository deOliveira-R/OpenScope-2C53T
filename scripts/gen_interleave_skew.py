#!/usr/bin/env python3
"""Generate firmware/src/dsp/interleave_skew_taps.h — the Farrow table of the
250 MS/s converter-B timing-skew correction (dsp/interleave.c).

Problem (two-channel time-interleaved ADC, TIADC). In the merged record even
samples come from converter A at their nominal times; odd samples come from
converter B, which samples `delta` merged samples away from its nominal time
(unit #2 and stock: B at 0.451 of a converter period after A instead of 0.5,
so delta = 2 * (0.451 - 0.5) = -0.098). For an odd output n the samples
around it sit at

    t_j = j + delta  for even j  (B samples, n + j odd)
    t_j = j          for odd j   (A samples, n + j even),   j = -M..M

and the correction is the time-varying FIR that reconstructs x(n) from them:
g = argmin integral_0^w0 |sum_j g_j exp(i w t_j) - 1|^2 dw (least squares
over the band [0, w0] of the MERGED rate; Johansson & Lowenborg,
"Reconstruction of nonuniformly sampled bandlimited signals by means of
time-varying discrete-time FIR filters", 2002). Because the taps reach both
converters' samples at the full 250 MS/s rate, it stays valid for content up
to w0 — unlike a fractional delay on B's own 125 MS/s samples, which aliases
above 62.5 MHz.

The taps depend on delta, a per-unit number known only at run time, so they
are stored as a Farrow structure: g_j(delta) = [j == 0] + sum_p C[p][j] delta^p
(p = 1..P). Delta = 0 is exactly the identity. The polynomial is fitted to
exact designs at Chebyshev nodes of [-DMAX, DMAX]. Nothing here is unit
specific.

Pure Python (no numpy): solves small systems by Gaussian elimination.
Usage: python3 scripts/gen_interleave_skew.py > firmware/src/dsp/interleave_skew_taps.h
"""
import cmath
import math
import sys

M = 8                  # 17 taps
W0 = 0.8 * math.pi     # band edge: 100 MHz at 250 MS/s
P = 4                  # Farrow order
DMAX = 0.3             # |delta| in merged samples (|B - 0.5| <= 0.15 period)
REG = 1e-9             # Tikhonov term: the sinc Gram matrix is ill-conditioned


def solve(a, b):
    n = len(b)
    m = [row[:] + [b[i]] for i, row in enumerate(a)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(m[r][c]))
        m[c], m[p] = m[p], m[c]
        for r in range(n):
            if r != c:
                f = m[r][c] / m[c][c]
                for k in range(c, n + 1):
                    m[r][k] -= f * m[c][k]
    return [m[i][n] / m[i][i] for i in range(n)]


def icos(w0, d):
    """integral_0^w0 cos(w d) dw"""
    return w0 if abs(d) < 1e-12 else math.sin(w0 * d) / d


def times(delta):
    return [j + (delta if j % 2 == 0 else 0.0) for j in range(-M, M + 1)]


def design(delta):
    t = times(delta)
    n = len(t)
    q = [[icos(W0, t[i] - t[j]) + (REG if i == j else 0.0) for j in range(n)] for i in range(n)]
    p = [icos(W0, t[i]) for i in range(n)]
    return solve(q, p)


def image_dbc(g, delta, w):
    e = sum(gj * cmath.exp(1j * w * tj) for gj, tj in zip(g, times(delta))) - 1.0
    return 20.0 * math.log10(abs(e) / 2.0 + 1e-15)


def main():
    nodes = [DMAX * math.cos(math.pi * (i + 0.5) / (2 * P + 2)) for i in range(2 * P + 2)]
    designs = [design(d) for d in nodes]
    vt = [[d ** p for p in range(1, P + 1)] for d in nodes]
    vtv = [[sum(r[i] * r[j] for r in vt) for j in range(P)] for i in range(P)]
    coef = []  # coef[j][p-1]
    for j in range(2 * M + 1):
        y = [g[j] - (1.0 if j == M else 0.0) for g in designs]
        coef.append(solve(vtv, [sum(vt[r][i] * y[r] for r in range(len(nodes))) for i in range(P)]))

    # Self-check: worst image spur of the Farrow taps over the delta range.
    worst = -999.0
    for k in range(-10, 11):
        d = DMAX * k / 10.0
        g = [(1.0 if j == M else 0.0) + sum(coef[j][p] * d ** (p + 1) for p in range(P))
             for j in range(2 * M + 1)]
        s = sum(g)
        g[M] += 1.0 - s
        for f in (1, 10, 30, 50, 70, 90):
            worst = max(worst, image_dbc(g, d, 2 * math.pi * f / 250.0))

    o = sys.stdout
    o.write("/*\n * interleave_skew_taps.h — GENERATED by scripts/gen_interleave_skew.py; do\n"
            " * not edit. Farrow table of the converter-B timing-skew correction\n"
            " * (dsp/interleave.c; the derivation is in the script).\n *\n")
    o.write(" *   g[j](delta) = [j == M] + sum_{p=1..P} IL_SKEW_FARROW[p-1][j] * delta^p\n")
    o.write(" *   M = %d (%d taps), band edge %.2f pi (%.0f MHz at 250 MS/s),\n"
            " *   P = %d, fitted for |delta| <= %.2f merged samples.\n" %
            (M, 2 * M + 1, W0 / math.pi, W0 / math.pi * 125.0, P, DMAX))
    o.write(" * Generator's self-check: worst image spur %.1f dBc over |delta| <= %.2f,\n"
            " * 1..90 MHz (exact arithmetic; the 8-bit record adds its own floor).\n */\n" %
            (worst, DMAX))
    o.write("#ifndef INTERLEAVE_SKEW_TAPS_H\n#define INTERLEAVE_SKEW_TAPS_H\n\n")
    o.write("#define IL_SKEW_M        %du\n" % M)
    o.write("#define IL_SKEW_TAPS     %du\n" % (2 * M + 1))
    o.write("#define IL_SKEW_P        %du\n" % P)
    o.write("#define IL_SKEW_DMAX     %.2ff\n\n" % DMAX)
    o.write("static const float IL_SKEW_FARROW[IL_SKEW_P][IL_SKEW_TAPS] = {\n")
    for p in range(P):
        vals = ", ".join("%.9ef" % coef[j][p] for j in range(2 * M + 1))
        o.write("    { %s },\n" % vals)
    o.write("};\n\n#endif\n")


if __name__ == "__main__":
    main()
