/*
 * Band-limited (windowed sin(x)/x) interpolation for the fast timebases
 * (parity C5).
 *
 * WHY. At codes 0x00-0x03 the converters run at their top rate whatever the
 * code (124.8 MS/s each, 249.7 MS/s merged; scope_timebase.c), so the codes
 * can only differ in how far the display zooms into the record. Stock zooms by
 * an integer factor L = 1000 / ratio (0x08030B4E..0x08030B6C: 10, 5, 2 with
 * one channel, 20, 10, 4, 2 with both) and fills the new columns with
 * "sinusoidal interpolation" (Update Log V1.1.0), a 16-tap Q15 polyphase FIR
 * at 0x0803D5D4 (docs/re/parity2_static.md s3.6). Linear or sample-and-hold
 * would draw a 40 MHz sine at 125 MS/s as a triangle; sin(x)/x draws the
 * band-limited signal the samples actually define.
 *
 * DESIGN (own, not stock's table). 16 taps, the output point between taps 7
 * and 8 like stock. Tap k sits t = k - 7 - d samples from the output, with
 * h = sinc(t) * Kaiser(t / 8, beta 5), each phase normalised to sum to exactly
 * 32768. Phases are d = k/20, k = 0..19, so every factor that divides 20 --
 * all of stock's -- indexes one table (phase p of factor L is row p * 20 / L).
 * Measured by tests/test_sinc_interp.c: gain flat to 0.4 x fs within 0.5 %
 * on every phase, and a sampled step overshoots by less than the ideal
 * (unwindowed, infinite) sin(x)/x reconstruction's own 14.1 %. The half-sample
 * row lands within ~250 LSB of stock's (same family, different window).
 * Generated by scripts/gen_sinc_interp.py; the test regenerates it.
 *
 * Pure C, no firmware includes: host-built by `make test-sinc-interp`.
 */
#ifndef SINC_INTERP_H
#define SINC_INTERP_H

#include <stdint.h>

#define SINC_INTERP_TAPS    16u
#define SINC_INTERP_PHASES  20u     /* rows: d = k / 20 */
#define SINC_INTERP_CENTER  7       /* tap 7 = the sample at or before the point */

/* The Q15 table, [phase][tap]. Row 0 is the identity (tap 7 = 32768). */
const int32_t *sinc_interp_row(uint8_t phase20);

/*
 * The band-limited value at time n + phase20/20 of src[0..n_src), rounded and
 * clamped to 0..255. Taps that fall outside the array repeat the edge sample
 * (a record edge is drawn flat, never read out of bounds). phase20 >= 20 is
 * reduced modulo 20. Phase 0 returns src[n] exactly.
 */
uint8_t sinc_interp_at(const uint8_t *src, int32_t n_src, int32_t n, uint8_t phase20);

/*
 * The same kernel at ANY phase, frac_x1000 / 1000 of a sample past src[n]
 * (0..999; outside that it is clamped). For the zoom while paused (parity
 * C14, paused_view.c), whose display ratio is whatever the held record's rate
 * and the current code make it, not a divisor of 20. The coefficients are the
 * two table rows either side of the phase, linearly blended (row 20 being the
 * identity on src[n + 1]): every row sums to 32768, so the blend keeps unity DC
 * gain exactly, and where the phase IS a row (frac_x1000 a multiple of 50) the
 * result is sinc_interp_at() bit for bit -- one kernel for both zooms.
 * The blend's departure from the generated kernel at the true phase is below
 * 0.1 LSB on a full-scale band-limited input (tests/test_sinc_interp.c).
 */
uint8_t sinc_interp_frac(const uint8_t *src, int32_t n_src, int32_t n, int32_t frac_x1000);

/* The blended taps sinc_interp_frac() applies, as floats summing to 1 (tap k
 * weighs src[n - 7 + k]); frac is in samples, clamped to [0, 1). For tests and
 * paused_view's pv_taps(). */
void sinc_interp_taps(float frac, float taps[SINC_INTERP_TAPS]);

#endif /* SINC_INTERP_H */
